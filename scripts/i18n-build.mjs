// Builds the browser catalogues public/i18n/<lang>.json from the English phrases
// (src/lib/i18n/ui/en/NN.json, arrays) and their translations (src/lib/i18n/ui/<lang>/NN.json,
// arrays of the same length). `node scripts/i18n-build.mjs --chunk` splits a fresh source.json
// into new English chunks holding only the phrases that are not translated yet.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";

const UI = new URL("../src/lib/i18n/ui/", import.meta.url);
const LANGS = ["th", "ro", "fi"];
const SIZE = 220;
const chunks = () => (existsSync(new URL("en/", UI)) ? readdirSync(new URL("en/", UI)).filter((f) => /^\d+\.json$/.test(f)).sort() : []);
const load = (dir, f) => JSON.parse(readFileSync(new URL(`${dir}/${f}`, UI), "utf8"));
const isPattern = (s) => /\{\d+\}/.test(s);

if (process.argv.includes("--chunk")) {
  const src = JSON.parse(readFileSync(new URL("source.json", UI), "utf8"));
  const known = new Set(chunks().flatMap((f) => load("en", f)));
  const fresh = [...src.exact, ...src.patterns].filter((s) => !known.has(s));
  mkdirSync(new URL("en/", UI), { recursive: true });
  let n = chunks().length;
  for (let i = 0; i < fresh.length; i += SIZE) writeFileSync(new URL(`en/${String(n++).padStart(2, "0")}.json`, UI), JSON.stringify(fresh.slice(i, i + SIZE), null, 1));
  console.log(`${fresh.length} new phrases in ${Math.ceil(fresh.length / SIZE)} chunk(s)`);
  process.exit(0);
}

const hash = createHash("sha256");
let problems = 0;
mkdirSync(new URL("../../../../public/i18n/", UI), { recursive: true });
for (const lang of LANGS) {
  const exact = {};
  const patterns = [];
  let missing = 0;
  for (const f of chunks()) {
    const en = load("en", f);
    const file = new URL(`${lang}/${f}`, UI);
    if (!existsSync(file)) { missing += en.length; continue; }
    const tr = JSON.parse(readFileSync(file, "utf8"));
    if (tr.length !== en.length) { console.error(`${lang}/${f}: ${tr.length} translations for ${en.length} phrases`); problems++; continue; }
    en.forEach((s, i) => {
      const t = tr[i];
      if (typeof t !== "string" || !t.trim()) { missing++; return; }
      // A translation may drop a placeholder (e.g. an English plural "s") but never invent one.
      const want = new Set(s.match(/\{\d+\}/g) ?? []);
      const got = t.match(/\{\d+\}/g) ?? [];
      const extra = got.filter((g) => !want.has(g));
      if (extra.length) { console.error(`${lang}/${f}#${i}: unknown placeholders ${extra.join()} in “${s}”`); problems++; return; }
      if (isPattern(s)) patterns.push([s, t]); else exact[s] = t;
    });
  }
  const json = JSON.stringify({ exact, patterns });
  hash.update(json);
  writeFileSync(new URL(`../../../../public/i18n/${lang}.json`, UI), json);
  console.log(`${lang}: ${Object.keys(exact).length} phrases, ${patterns.length} patterns${missing ? `, ${missing} not translated` : ""}`);
}
writeFileSync(new URL("version.ts", UI), `// Generated by scripts/i18n-build.mjs — changes whenever a catalogue changes, so browsers fetch the new one.\nexport const CATALOG_VERSION = "${hash.digest("hex").slice(0, 12)}";\n`);
if (problems) process.exit(1);
